type I18nContextValue = {
  locale: AppLocale;
  localeTag: "en-US" | "zh-CN";
  setLocale: (locale: AppLocale) => void;
  t: (message: string, values?: TranslationValues) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function initialLocale(): AppLocale {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "zh-CN") return stored;
  } catch {
    // Storage may be disabled. Browser language remains a safe fallback.
  }
  return navigator.languages.some((language) => language.toLocaleLowerCase().startsWith("zh")) ? "zh-CN" : "en";
}

function interpolate(message: string, values?: TranslationValues): string {
  if (!values) return message;
  return message.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, key: string) => String(values[key] ?? match));
}

export function translateMessage(locale: AppLocale, message: string, values?: TranslationValues): string {
  return interpolate(locale === "zh-CN" ? zhCN[message] ?? message : message, values);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<AppLocale>(initialLocale);
  const setLocale = useCallback((next: AppLocale) => {
    setLocaleState(next);
    try { window.localStorage.setItem(STORAGE_KEY, next); } catch { /* optional persistence */ }
  }, []);
  const t = useCallback((message: string, values?: TranslationValues) => translateMessage(locale, message, values), [locale]);

  useEffect(() => {
    document.documentElement.lang = locale === "zh-CN" ? "zh-CN" : "en";
    document.title = locale === "zh-CN" ? "小说世界编译器" : "Novel World Harness";
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    localeTag: locale === "zh-CN" ? "zh-CN" : "en-US",
    setLocale,
    t,
  }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider.");
  return context;
}

export function LanguageSwitcher() {
  const { locale, setLocale, t } = useI18n();
  return (
    <div className="language-switcher" role="group" aria-label={t("Interface language")}>
      <button type="button" aria-pressed={locale === "en"} onClick={() => setLocale("en")}>EN</button>
      <button type="button" aria-pressed={locale === "zh-CN"} onClick={() => setLocale("zh-CN")}>中文</button>
    </div>
  );
}
